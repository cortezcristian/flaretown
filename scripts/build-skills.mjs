// Bundled skills (task 017): reads skills/<name>/ and writes src/skills/bundled.generated.ts,
// a map of skill name -> { path: text content }. Runs before every build and typecheck.
// Text files only; the runtime parses SKILL.md (agents/skills parseSkillMarkdown).
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const skillsDir = join(root, "skills");
const out = join(root, "src", "skills", "bundled.generated.ts");
const MAX_BYTES = 512 * 1024;

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const bundled = {};
let names = [];
try {
  names = readdirSync(skillsDir).filter((n) => statSync(join(skillsDir, n)).isDirectory());
} catch {
  /* no skills folder */
}
for (const name of names.sort()) {
  const dir = join(skillsDir, name);
  const files = {};
  let size = 0;
  for (const file of walk(dir).sort()) {
    const buf = readFileSync(file);
    if (buf.includes(0)) continue; // binary
    size += buf.length;
    files[relative(dir, file).split("\\").join("/")] = buf.toString("utf8");
  }
  if (!files["SKILL.md"]) throw new Error(`skills/${name} has no SKILL.md`);
  if (size > MAX_BYTES) throw new Error(`skills/${name} is over ${MAX_BYTES} bytes`);
  bundled[name] = files;
}

mkdirSync(join(root, "src", "skills"), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-skills.mjs from skills/. Don't edit.\nexport const BUNDLED_SKILLS: Record<string, Record<string, string>> = ${JSON.stringify(bundled, null, 2)};\n`,
);
console.log(`build-skills: ${names.length} bundled skill(s)`);
